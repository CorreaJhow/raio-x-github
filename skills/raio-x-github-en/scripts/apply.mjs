#!/usr/bin/env node
// Step 6: turns plan.json (reviewed with the dev) into apply.sh.
// The generated script simulates by default; it only executes with --apply. It never deletes a repo.
// Usage: node apply.mjs [folder=xray]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const q = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;
const PROFILE_FIELDS = { bio: '-f bio', blog: '-f blog', name: '-f name', company: '-f company', location: '-f location', hireable: '-F hireable' };

function step(a, U) {
  const R = `"$U/${a.repo}"`;
  switch (a.type) {
    case 'private':
      return `run ${q(`gh repo edit ${U}/${a.repo} --visibility public --accept-visibility-change-consequences`)} gh repo edit ${R} --visibility private --accept-visibility-change-consequences`;
    case 'archive':
      return `run ${q(`gh repo unarchive ${U}/${a.repo} --yes`)} gh repo archive ${R} --yes`;
    case 'description':
      return `run ${q(`gh repo edit ${U}/${a.repo} --description ${q(a.previous ?? '')}`)} gh repo edit ${R} --description ${q(a.value)}`;
    case 'homepage':
      return `run ${q(`gh repo edit ${U}/${a.repo} --homepage ${q(a.previous ?? '')}`)} gh repo edit ${R} --homepage ${q(a.value)}`;
    case 'topics': {
      const t = [].concat(a.value).join(',');
      return `run ${q(`gh repo edit ${U}/${a.repo} --remove-topic ${t}`)} gh repo edit ${R} --add-topic ${q(t)}`;
    }
    case 'profile': {
      const f = PROFILE_FIELDS[a.field];
      if (!f) throw new Error(`unknown profile field: ${a.field}`);
      return `user_scope\nrun ${q(`gh api -X PATCH user ${f}=${q(a.previous ?? '')}`)} gh api -X PATCH user ${f}=${q(a.value)}`;
    }
    case 'clean-coauthor':
      return `clean_coauthor ${q(a.repo)}`;
    default:
      throw new Error(`unsupported action type: ${a.type} (the X-ray never deletes a repo)`);
  }
}

export function generateScript(plan, now = new Date()) {
  const body = plan.actions.map((a) => {
    const title = `step ${q(`${a.id}. ${a.type}${a.repo ? ` ${a.repo}` : ` ${a.field}`}: ${a.reason ?? ''}`)}`;
    if (a.pending) return `${title}\necho "  skipped: pending (${String(a.pending).replace(/"/g, "'")})"`;
    return `${title}\n${step(a, plan.login)}`;
  });
  return `#!/usr/bin/env bash
# Generated by github-xray on ${now.toISOString().slice(0, 16).replace('T', ' ')}. Review before running.
#   bash apply.sh            -> only shows what it would do (nothing changes)
#   bash apply.sh --apply    -> executes
# No step deletes a repo. Each step prints how to undo it.
set -u
U=${q(plan.login)}
APPLY=0; [ "\${1:-}" = "--apply" ] && APPLY=1
HERE="$(cd "$(dirname "$0")" && pwd)"
[ $APPLY = 1 ] && echo "APPLY MODE: this will change the account $U" || echo "DRY RUN: nothing will be changed. Use --apply to execute."

step() { echo; echo "== $1"; }
# run <undo> <command...>
run() {
  local undo=$1; shift
  echo "  command:  $(printf '%q ' "$@")"
  echo "  undo:     $undo"
  [ $APPLY = 1 ] || return 0
  "$@" >/dev/null && echo "  ok" || echo "  FAILED"
}
# Changing the profile needs gh's 'user' scope, which opens a browser login once.
user_scope() {
  gh auth status 2>&1 | grep -q "'user'" && return 0
  echo "  warning: gh is missing the 'user' scope; with --apply it will open the browser to authorize"
  [ $APPLY = 1 ] && gh auth refresh -h github.com -s user
}
# Removes AI co-author/footer from commit messages (branches and tags), with a --mirror backup first.
clean_coauthor() {
  local repo=$1 url="https://github.com/$U/$1.git"
  local bkp="$HERE/backup/$repo-$(date +%Y%m%d-%H%M%S).git" tmp="$HERE/rewrite/$repo.git"
  echo "  backup:    git clone --mirror $url $bkp"
  echo "  rewrite:   git filter-branch --msg-filter (removes AI Co-authored-by and 'Generated with Claude Code')"
  echo "  publish:   git push --force $url (branches and tags)"
  echo "  undo:      git -C $bkp push --force $url 'refs/heads/*:refs/heads/*' 'refs/tags/*:refs/tags/*'"
  echo "  warning:   old commits in closed PRs (refs/pull) stay on GitHub; local copies need fetch + reset"
  [ $APPLY = 1 ] || return 0
  git clone --mirror -q "$url" "$bkp" || { echo "  FAILED backup: nothing changed"; return 1; }
  rm -rf "$tmp"
  # bare from the backup: no refs/pull and no mirror flag (push from a --mirror clone does not accept a refspec)
  git clone --bare -q "$bkp" "$tmp"
  FILTER_BRANCH_SQUELCH_WARNING=1 git -C "$tmp" filter-branch -f --msg-filter \\
    "{ grep -viE '^co-authored-by:.*(anthropic|claude|copilot|cursor|openai|codex|devin)|generated with \\\\[?claude code' || true; }" \\
    -- --branches --tags >/dev/null || { echo "  FAILED rewrite: nothing changed on GitHub"; return 1; }
  git -C "$tmp" push --force -q "$url" 'refs/heads/*:refs/heads/*' 'refs/tags/*:refs/tags/*' && echo "  ok" || echo "  FAILED push"
}

${body.join('\n\n')}

echo
[ $APPLY = 1 ] && echo "Done." || echo "End of dry run: nothing was changed."
echo "By hand (the API can't): pinned repos in Profile > Customize your pins (list in REPORT.md)."
`;
}

if (process.argv[1]?.endsWith('apply.mjs')) {
  const folder = process.argv[2] || 'xray';
  const plan = JSON.parse(readFileSync(join(folder, 'plan.json'), 'utf8'));
  writeFileSync(join(folder, 'apply.sh'), generateScript(plan), { mode: 0o755 });
  const pend = plan.actions.filter((a) => a.pending).length;
  console.log(`ok  ${join(folder, 'apply.sh')}: ${plan.actions.length} step(s), ${pend} pending`);
}
